    public static void build(
        ItemMappingRegistry registry,
        Path outputZip,
        Map<JavaPackReader.CmdKey, JavaPackReader.JavaModelDefinition> javaPackEntries,
        Map<String, JavaPackReader.JavaModelDefinition> directItemModels,
        AttachableGenerationConfig attachableConfig,
        Map<String, Path> entityTextureCopies,
        Map<String, Path> armorTextureCopies,
        com.geyserextra.core.config.GeyserExtraConfig.ArmorGenerationConfig armorConfig,
        Logger logger,
        boolean debug
    ) throws IOException {
        Collection<CustomItemMapping> mappings = registry.getMappings();
        if (javaPackEntries == null) {
            javaPackEntries = Collections.emptyMap();
        }
        Map<String, JavaPackReader.JavaModelDefinition> effectiveDirectModels =
            directItemModels != null ? directItemModels : Collections.emptyMap();
        // Defensive: a null map is treated as "no entity texture overrides
        // requested", preserving the pre-Phase-7b zip layout exactly. Only
        // non-empty maps mutate the generated zip contents.
        Map<String, Path> effectiveEntityCopies = entityTextureCopies != null
            ? entityTextureCopies
            : Collections.emptyMap();
        // Null-guard: callers that don't care about attachables pass null;
        // treat that as "off" so the rest of the pipeline sees a non-null
        // policy object without forcing generation.
        AttachableGenerationConfig effectiveConfig = attachableConfig != null
            ? attachableConfig
            : new AttachableGenerationConfig(AttachableGenerationConfig.MODE_OFF, false);
        boolean attachableMode = !AttachableGenerationConfig.MODE_OFF.equals(effectiveConfig.mode());

        Path parent = outputZip.getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }

        // Codex round-4/5 fix (I1 + J1): pre-read every armor AND entity PNG
        // ONCE here so the hash (Phase 2) and the zip write (Phase 3)
        // consume the same byte buffer. Two independent Files.readAllBytes
        // calls would otherwise open a window where the hash-time read
        // fails (transient AV lock, Windows sharing violation, etc.) while
        // the write-time read succeeds — flipping the zip contents without
        // flipping the patch version. Failed reads here drop the texture
        // from BOTH the hash and the zip in lockstep, keeping
        // (UUID, version) honest for cache invalidation.
        Map<String, byte[]> armorTextureBytes = new LinkedHashMap<>();
        if (armorTextureCopies != null && !armorTextureCopies.isEmpty()) {
            for (Map.Entry<String, Path> entry : armorTextureCopies.entrySet()) {
                String iconKey = entry.getKey();
                Path source = entry.getValue();
                if (source == null) {
                    continue;
                }
                try {
                    armorTextureBytes.put(iconKey, Files.readAllBytes(source));
                } catch (IOException ex) {
                    if (logger != null) {
                        logger.warning("[AutoPack] failed to read armor texture "
                            + source + " for iconKey " + iconKey + ": "
                            + ex.getClass().getSimpleName() + ": " + ex.getMessage()
                            + " — armor attachable AND PNG copy will be skipped for "
                            + "this mapping (Bedrock falls back to vanilla armor).");
                    }
                }
            }
        }
        // Same lockstep treatment for entity texture overrides (Codex J1):
        // in-place edits to a Java pack entity PNG must flip the manifest
        // patch version so Bedrock clients drop their cached pack.
        Map<String, byte[]> entityTextureBytes = new LinkedHashMap<>();
        for (Map.Entry<String, Path> entry : effectiveEntityCopies.entrySet()) {
            String zipPath = entry.getKey();
            Path source = entry.getValue();
            if (source == null) {
                continue;
            }
            try {
                entityTextureBytes.put(zipPath, Files.readAllBytes(source));
            } catch (IOException ex) {
                if (logger != null) {
                    logger.warning("[AutoPack] failed to read entity texture "
                        + source + " -> " + zipPath + ": "
                        + ex.getClass().getSimpleName() + ": " + ex.getMessage()
                        + " — entity override will be skipped for this mapping "
                        + "(Bedrock falls back to vanilla entity texture).");
                }
            }
        }

        // Phase 1 - plan the PNG copies (without writing yet) so we know the
        // final customIconToTexturePath before we serialize the manifest.
        // Writing PNGs to disk only happens inside phase 3 below, against the
        // tmp file. This separation also lets phase 2 hash the rendered
        // item_texture.json without re-serializing on the hot write path.
        Map<String, String> customIconToTexturePath = new LinkedHashMap<>();
        List<TextureCopyTask> pngTasks = new ArrayList<>();
        Set<String> plannedZipEntries = new HashSet<>();
        // Phase 3: plan attachable artifacts alongside textures. Key is the
        // ZIP entry path; value is the UTF-8-ready JSON. We collect them in a
        // LinkedHashMap so the iteration order (and therefore the patch hash)
        // remains deterministic.
        Map<String, String> attachableArtifacts = new LinkedHashMap<>();
        int duplicateSkipCount = 0;
        for (CustomItemMapping mapping : mappings) {
            JavaPackReader.CmdKey key = new JavaPackReader.CmdKey(
                mapping.baseItem(), mapping.customModelData());
            JavaPackReader.JavaModelDefinition def = mapping.hasItemModelId()
                ? effectiveDirectModels.get(mapping.itemModelId())
                : javaPackEntries.get(key);
            if (def == null) {
                continue;
            }
            String iconKey = toBedrockIconKey(mapping.name());
            // Zip paths embed the (possibly shortened) file base, never the
            // raw icon key: Geyser warns at 80-char entry paths and some
            // Bedrock platforms fail to load such packs. The icon key itself
            // (item_texture.json key / attachable identifier) stays full.
            String fileBase = zipSafeFileBase(iconKey);
            String bedrockTextureRelative = "textures/items/" + fileBase;
            String zipEntry = bedrockTextureRelative + ".png";
            if (!plannedZipEntries.add(zipEntry)) {
                duplicateSkipCount++;
                if (logger != null) {
                    logger.warning("[AutoPack] duplicate ZIP entry skipped (mapping name "
                        + "collides with already-written entry): " + zipEntry
                        + " (mapping=" + mapping.name() + ", key=" + key + ")");
                }
                continue;
            }
            JavaModelDisplay.Transform guiTransform =
                def.display() != null ? def.display().gui() : null;
            pngTasks.add(new TextureCopyTask(
                def.textureFile(), zipEntry, key.toString(), iconKey, guiTransform,
                def.geometry(), def.textureFiles()));
            customIconToTexturePath.put(iconKey, bedrockTextureRelative);

            // Phase 7a: armor-equipped items route through the armor
            // attachable path (referencing geometry.humanoid.armor.<slot>)
            // instead of the held-item attachable. We emit BOTH the armor
            // attachable AND keep the inventory icon, since Bedrock players
            // see the icon in their inventory slots and the armor mesh when
            // the item is worn.
            //
            // Codex round-1 fix: the armor attachable references
            // textures/entity/equipment/<iconKey>.png, which is only present
            // when scanArmorTextureCopies successfully resolved the equipment
            // JSON. Emitting the attachable without the texture leaves a
            // dangling reference and Bedrock renders magenta/missing. Gate
            // emission on the texture actually being in the planned copies;
            // otherwise skip both armor AND held-item attachable so Bedrock
            // falls back to vanilla armor rendering for the base material.
            boolean armorEnabled = mapping.hasArmor()
                && armorConfig != null && armorConfig.enabled();
            // Gate on the pre-read bytes map (Codex I1 fix), not the raw
            // path map, so an entry whose source PNG failed to read here
            // produces neither an armor attachable nor a PNG zip entry —
            // hash and zip stay in lockstep.
            boolean armorTextureResolved = armorEnabled
                && armorTextureBytes.containsKey(iconKey);

            // Phase 7a emission split (Codex G2 + H2 fixes):
            //   armor texture resolved          → emit armor attachable, skip held-item
            //   armor enabled, no texture       → log WARN (unconditionally),
            //                                     fall through to held-item path
            //                                     when attachableMode is on so the
            //                                     in-hand view is preserved
            //   not armor                       → existing held-item path
            //
            // H2 fix: the diagnostic WARN for unresolved armor textures used
            // to live inside the `else if (attachableMode)` branch, which
            // silently swallowed the message when attachableGeneration is
            // off. Hoisting it out makes the failure visible regardless of
            // attachable mode, so operators always learn why the worn-state
            // fallback kicked in.
            if (armorEnabled && !armorTextureResolved && logger != null) {
                logger.warning("[AutoPack] armor mapping " + mapping.name()
                    + " (slot=" + mapping.armor().slot()
                    + ", asset_id=" + mapping.armor().assetId() + ") "
                    + "has no resolved equipment texture in any configured Java pack — "
                    + "skipping armor attachable; Bedrock will render vanilla armor for "
                    + mapping.baseItem()
                    + " when worn"
                    + (attachableMode
                        ? ". Held-item attachable still emitted for in-hand view."
                        : "."));
            }
            if (armorTextureResolved) {
                Map<String, String> armorArt = BedrockAttachableWriter.buildArmorArtifacts(
                    iconKey, fileBase, mapping.armor(), armorConfig);
                for (Map.Entry<String, String> a : armorArt.entrySet()) {
                    String artifactPath = a.getKey();
                    if (!plannedZipEntries.add(artifactPath)) {
                        if (logger != null) {
                            logger.fine("[AutoPack] armor attachable already planned, skipping: "
                                + artifactPath);
                        }
                        continue;
                    }
                    attachableArtifacts.put(artifactPath, a.getValue());
                }
                // Don't emit the held-item attachable for armor: identifier
                // collision would have only one win on Bedrock side anyway,
                // and the armor path is the visually correct one when worn.
            } else if (attachableMode) {
                // Phase 3/4/6: held-item attachable. Reached for both regular
                // mappings AND for armor mappings whose equipment texture
                // could not be resolved (the WARN above already surfaced the
                // missing-texture case). The held-item attachable still
                // provides the in-hand 2D/3D rendering that pre-Phase-7
                // builds offered for these items.
                int[] textureSize = probePngDimensions(def.textureFile(), logger);
                Map<String, String> artifacts = BedrockAttachableWriter.buildArtifacts(
                    iconKey, fileBase, def.display(), def.geometry(),
                    bedrockTextureRelative, textureSize[0], textureSize[1],
                    effectiveConfig, logger);
                for (Map.Entry<String, String> art : artifacts.entrySet()) {
                    String artifactPath = art.getKey();
                    if (!plannedZipEntries.add(artifactPath)) {
                        if (logger != null) {
                            logger.fine("[AutoPack] attachable artifact already planned, skipping: "
                                + artifactPath);
                        }
                        continue;
                    }
                    attachableArtifacts.put(artifactPath, art.getValue());
                }
            }
        }

        // Phase 2 - render item_texture.json from the finalised iconKey map
        // and derive a content-addressed patch version. The patch version
        // changes whenever item_texture.json OR any attachable artifact
        // changes, which is what tells Bedrock clients "this is a new pack,
        // drop your cached copy". Without this the manifest UUID + version
        // pair stays constant across pack regenerations and the client
        // silently keeps using stale textures or stale attachables.
        // Codex round-6 fix (K1): apply the byte-lockstep pattern to
        // ordinary item PNGs too. The Phase 1 planner has already populated
        // pngTasks with source paths; pre-read those bytes here so the
        // hash and the Phase 3 zip write reference the same buffer. Read
        // failures cascade-clean: the failed icon's entry is dropped from
        // customIconToTexturePath (so item_texture.json doesn't claim it
        // exists), from any planned attachable artifacts (so there's no
        // dangling reference), and from pngTasks (so the zip write skips
        // it). This keeps hash and zip in lockstep across every texture
        // category — items, entity overrides, and armor textures.
        Map<String, byte[]> itemTextureBytes = new LinkedHashMap<>();
        java.util.Iterator<TextureCopyTask> taskIter = pngTasks.iterator();
        while (taskIter.hasNext()) {
            TextureCopyTask task = taskIter.next();
            try {
                // Raw PNG always stays at the model path (attachable UVs).
                // INV/drop icon: bake Java display.gui only (no trim/crop).
                // Crop-to-non-square warped under Bedrock slot scaling;
                // stretch-fit caused pixel artifacts. Gui bake matches Java's
                // inventory algorithm (scale/translation/Z-rot); scale>1 may
                // clip at canvas edges the same way Java slots do.
                byte[] raw = Files.readAllBytes(task.source());
                itemTextureBytes.put(task.zipEntry(), raw);
                // A model built from `elements` samples regions of an atlas,
                // so the raw PNG is a UV sheet rather than a picture of the
                // item — that is what Bedrock was showing in inventories,
                // dropped items and item frames. Render the model instead,
                // which is what Java does live when it draws a slot. Falls
                // back to the 2D affine bake when there is no geometry (flat
                // texture-swap items, whose PNG already is the icon) or when
                // the render produces nothing.
                byte[] invIcon = renderModelIcon(task, raw, logger);
                if (invIcon == null) {
                    invIcon = GuiIconTransformer.bake(raw, task.gui(), logger);
                }
                if (invIcon != raw) {
                    String zipEntry = task.zipEntry();
                    if (zipEntry.startsWith("textures/items/") && zipEntry.endsWith(".png")) {
                        String guiTextureRelative =
                            zipEntry.substring(0, zipEntry.length() - ".png".length()) + "_gui";
                        String guiEntry = guiTextureRelative + ".png";
                        if (plannedZipEntries.add(guiEntry)) {
                            itemTextureBytes.put(guiEntry, invIcon);
                            customIconToTexturePath.put(task.iconKey(), guiTextureRelative);
                        } else if (logger != null) {
                            logger.warning("[AutoPack] inv-icon entry collides with an "
                                + "existing entry, keeping raw icon: " + guiEntry);
                        }
                    }
                }
            } catch (IOException ex) {
                if (logger != null) {
                    logger.warning("[AutoPack] failed to read item texture "
                        + task.source() + " -> " + task.zipEntry() + ": "
                        + ex.getClass().getSimpleName() + ": " + ex.getMessage()
                        + " — texture and any planned attachable artifacts will be "
                        + "dropped for this mapping (Bedrock falls back to vanilla).");
                }
                taskIter.remove();
                // The task carries the real icon key (the zip entry may embed
                // a shortened file base, so path-stripping would recover the
                // wrong key for 80-char-shortened names).
                String zipEntry = task.zipEntry();
                String iconKey = task.iconKey();
                if (iconKey != null) {
                    customIconToTexturePath.remove(iconKey);
                    // Artifact entry paths were planned with the shortened
                    // file base — recompute it the same (deterministic) way.
                    String fileBase = zipSafeFileBase(iconKey);
                    String attachableEntry = BedrockAttachableWriter.attachableEntryPath(fileBase);
                    String geometryEntry = BedrockAttachableWriter.geometryEntryPath(fileBase);
                    String animationEntry = BedrockAttachableWriter.animationEntryPath(fileBase);
                    attachableArtifacts.remove(attachableEntry);
                    attachableArtifacts.remove(geometryEntry);
                    attachableArtifacts.remove(animationEntry);
                    // Codex round-7 optional cleanup: also drop the removed
                    // entries from plannedZipEntries so the deduplication set
                    // stays symmetric with the actual zip contents. The set
                    // is not consulted after Phase 1 in the current flow, so
                    // this is cosmetic correctness rather than a behavioural
                    // fix — but keeping the data structures in sync prevents
                    // a future caller from observing inconsistent state.
                    plannedZipEntries.remove(zipEntry);
                    plannedZipEntries.remove(attachableEntry);
                    plannedZipEntries.remove(geometryEntry);
                    plannedZipEntries.remove(animationEntry);
                }
            }
        }

        // Bedrock names a custom item by looking its identifier up in the
        // pack's texts/*.lang; with no entry the client shows the raw
        // identifier, which is what surfaced as "item names are item IDs".
        // Built from ALL mappings, not just the ones that resolved a model:
        // an item the extension registers but the pack has no texture for
        // still needs a name.
        itemTextureBytes.putAll(buildLangFiles(mappings, logger));

        String itemTextureJson = buildItemTextureJson(mappings, customIconToTexturePath, logger, debug);
        // Codex round-2/3/4/5/6 fix (G1 + H1 + I1 + J1 + K1): item, entity,
        // and armor textures all feed PRE-READ PNG bytes into the patch
        // hash. Hash and zip share the same byte buffer for every texture
        // category, so any in-place PNG edit flips the manifest version
        // and Bedrock clients drop stale cached packs reliably.
        int contentPatch = patchVersionFromContent(itemTextureJson, attachableArtifacts,
            entityTextureBytes, armorTextureBytes, itemTextureBytes);
        // readPackVersionState() carries the last known hash forward across
        // a promote (see its fallback branch): when the freshly built
        // .pending.zip content hashes identically to what is already active,
        // patchVersion below comes out equal to the version already on
        // disk/cached by Bedrock clients. That is intentional, not a bug —
        // identical bytes deserve an identical version so clients keep their
        // cache instead of re-downloading a pack that did not actually
        // change.
        PackVersionState prior = readPackVersionState(outputZip, logger);
        int patchVersion = nextMonotonicPatchVersion(
            contentPatch, prior.lastPatch(), prior.lastContentHash(), prior.hasContentHash());
        if (logger != null && patchVersion != contentPatch) {
            logger.info("[AutoPack] manifest patch " + contentPatch
                + " raised to monotonic " + patchVersion
                + " (last emitted " + prior.lastPatch() + ")");
        }
        if (logger != null && patchVersion >= MAX_PACK_SEQUENCE) {
            // Nothing higher can be emitted for this UUID, so from here on
            // clients keep whatever they cached no matter what changes. Loud
            // because it is otherwise invisible — the pack still builds fine.
            logger.severe("[AutoPack] pack version sequence is saturated at "
                + patchVersion + ". Bedrock clients will no longer see updates for UUID "
                + HEADER_UUID + "; rotate the pack UUID to recover.");
        }
        // Any geometry emitted at format 1.21.0 (per-face uv_rotation) forces
        // the manifest to advertise the matching engine version — see
        // buildManifestJson.
        String manifestJson = buildManifestJson(
            patchVersion, requiresModernGeometry(attachableArtifacts));

        // Phase 3 — write everything to a sibling .tmp file, then atomic-move
        // into place. Without the tmp + atomic move, a Bedrock client
        // streaming the previous pack mid-regeneration would read a corrupt
        // (truncated) ZIP because Files.newOutputStream defaults to
        // CREATE + TRUNCATE_EXISTING. The atomic move guarantees the visible
        // file flips from one valid ZIP to the next in a single filesystem
        // operation; readers only ever see complete packs.
        Path tmpZip = outputZip.resolveSibling(outputZip.getFileName() + ".tmp");
        Set<String> writtenEntries = new HashSet<>();
        int textureCopyCount = 0;
        try (ZipOutputStream zos = new ZipOutputStream(Files.newOutputStream(tmpZip))) {
            putEntryUnique(zos, "manifest.json",
                manifestJson.getBytes(StandardCharsets.UTF_8), writtenEntries, logger);
            putEntryUnique(zos, "pack_icon.png", buildPackIconPng(), writtenEntries, logger);

            // Codex K1 fix: write item PNGs from the pre-read bytes buffer
            // (populated alongside the hash) instead of re-reading each
            // source via Files.readAllBytes. The second read was the
            // window where transient I/O could let the hash see one set of
            // bytes and the zip see another. Entries that failed the
            // single pre-read were already removed from pngTasks +
            // itemTextureBytes, so this loop only writes what the hash
            // already accounted for.
            for (TextureCopyTask task : pngTasks) {
                byte[] pngBytes = itemTextureBytes.get(task.zipEntry());
                if (pngBytes == null) {
                    // Defensive: should be impossible because the pre-read
                    // and pngTasks were cleaned in lockstep, but guard anyway.
                    if (logger != null) {
                        logger.fine("[AutoPack] missing pre-read bytes for "
                            + task.zipEntry() + " — skipping copy.");
                    }
                    continue;
                }
                putEntryUnique(zos, task.zipEntry(), pngBytes, writtenEntries, logger);
                textureCopyCount++;
                if (debug && logger != null) {
                    logger.fine("[AutoPack] copied " + task.source() + " -> " + task.zipEntry());
                }
            }

            // Gui-baked icon variants ("<iconKey>_gui.png") live only in
            // itemTextureBytes — they have no TextureCopyTask because their
            // bytes are derived, not copied from disk. Write everything the
            // pngTasks loop above didn't already emit so the zip matches the
            // hash input exactly.
            for (Map.Entry<String, byte[]> derived : itemTextureBytes.entrySet()) {
                if (writtenEntries.contains(derived.getKey())) {
                    continue;
                }
                putEntryUnique(zos, derived.getKey(), derived.getValue(), writtenEntries, logger);
                textureCopyCount++;
            }

            putEntryUnique(zos, "textures/item_texture.json",
                itemTextureJson.getBytes(StandardCharsets.UTF_8), writtenEntries, logger);

            // Phase 3 (this release): write attachable / geometry / animation
            // JSONs planned earlier. mode=off produces an empty map, so this
            // loop is a strict no-op for callers that disable the feature —
            // preserving bit-for-bit identity with the pre-Phase-3 build.
            for (Map.Entry<String, String> art : attachableArtifacts.entrySet()) {
                putEntryUnique(zos, art.getKey(),
                    art.getValue().getBytes(StandardCharsets.UTF_8), writtenEntries, logger);
            }

            // Phase 7b (Codex J1 fix): write entity textures from the
            // pre-read bytes buffer (populated at the top of build()) so
            // the hash and zip share the same byte sequence. Read failures
            // already dropped those entries from entityTextureBytes at
            // planning time, keeping hash and zip in lockstep.
            for (Map.Entry<String, byte[]> entityCopy : entityTextureBytes.entrySet()) {
                putEntryUnique(zos, entityCopy.getKey(), entityCopy.getValue(),
                    writtenEntries, logger);
            }

            // Phase 7a: copy armor textures from the pre-read bytes buffer
            // (populated at the top of build()) so the hash above and the
            // zip write here consume the SAME byte sequence. Entries whose
            // source PNG failed to read at planning time were already
            // dropped from armorTextureBytes, ensuring hash and zip cannot
            // disagree on what's present in the pack.
            for (Map.Entry<String, byte[]> armorCopy : armorTextureBytes.entrySet()) {
                String iconKey = armorCopy.getKey();
                // Same shortened file base the armor attachable's textures
                // reference was built with (zipSafeFileBase is deterministic).
                String zipEntry = BedrockAttachableWriter.armorTextureEntryPath(
                    zipSafeFileBase(iconKey));
                putEntryUnique(zos, zipEntry, armorCopy.getValue(), writtenEntries, logger);
            }
        } catch (IOException ioEx) {
            // Failed to fully write the tmp file — make sure it doesn't
            // accumulate on disk before propagating the error.
            try {
                Files.deleteIfExists(tmpZip);
            } catch (IOException cleanupEx) {
                if (logger != null) {
                    logger.log(Level.WARNING,
                        "[AutoPack] failed to clean up tmp file after write error", cleanupEx);
                }
            }
            throw ioEx;
        }

        // If the freshly built zip is byte-identical to what's already on
        // disk, leave the existing file untouched. Geyser caches the pack at
        // ITS startup and file-watches it afterwards; replacing the file
        // mid-serve (even with identical content, some filesystems bump
        // metadata) triggers "Detected a change in the resource pack" and
        // risks serving a mismatched pack to joining Bedrock clients. The
        // deterministic entry timestamps set in putEntry make this
        // comparison meaningful across rebuilds.
        try {
            if (Files.exists(outputZip)
                && Files.size(outputZip) == Files.size(tmpZip)
                && java.util.Arrays.equals(
                    Files.readAllBytes(outputZip), Files.readAllBytes(tmpZip))) {
                Files.deleteIfExists(tmpZip);
                if (logger != null) {
                    logger.fine("[AutoPack] pack content unchanged — existing zip kept as-is.");
                }
                writePackVersionState(outputZip, patchVersion, contentPatch, logger);
                writeBlockIconBasesSidecar(
                    outputZip, customIconToTexturePath.keySet(), logger);
                return;
            }
        } catch (IOException cmpEx) {
            // Comparison is a best-effort optimisation; on any I/O hiccup
            // fall through to the normal replace path.
            if (logger != null) {
                logger.fine("[AutoPack] unchanged-content check failed ("
                    + cmpEx.getMessage() + ") — proceeding with replace.");
            }
        }

        // FINE, not WARNING: a changed pack at boot (before Geyser enables)
        // is the normal update path. Only mid-serve changes are risky, and
        // Geyser itself already emits a WARN for those.
        if (logger != null && Files.exists(outputZip)) {
            logger.fine("[AutoPack] pack content changed since the last build — "
                + "if Geyser is already running, restart it so Bedrock clients "
                + "receive a consistent pack.");
        }

        try {
            Files.move(tmpZip, outputZip,
                StandardCopyOption.REPLACE_EXISTING,
                StandardCopyOption.ATOMIC_MOVE);
        } catch (IOException atomicEx) {
            // Some filesystems (e.g. cross-mount, certain Windows network
            // shares) don't support ATOMIC_MOVE. Fall back to REPLACE_EXISTING
            // alone — the worst case is a brief window where a concurrent
            // reader sees the new file in a partially-readable state, which
            // is still strictly better than the previous "truncate then
            // append" path.
            if (logger != null) {
                logger.warning("[AutoPack] atomic move not supported on this filesystem ("
                    + atomicEx.getMessage() + "); falling back to non-atomic replace");
            }
            Files.move(tmpZip, outputZip, StandardCopyOption.REPLACE_EXISTING);
        }

        writePackVersionState(outputZip, patchVersion, contentPatch, logger);
        writeBlockIconBasesSidecar(
            outputZip, customIconToTexturePath.keySet(), logger);

        if (logger != null && !javaPackEntries.isEmpty()) {
            logger.fine("[AutoPack] Java pack texture copy: " + textureCopyCount
                + " custom textures applied, "
                + (mappings.size() - textureCopyCount - duplicateSkipCount)
                + " fell back to vanilla, "
                + duplicateSkipCount + " skipped due to duplicate ZIP entry name");
        }
        if (logger != null && attachableMode) {
            // Each item contributes either 0 or 3 attachable artifacts
            // (attachable + geometry + animation), so the count of attachable
            // ZIP entries divided by 3 gives the number of items that
            // successfully produced a held-item rendering.
            int attachableItemCount = attachableArtifacts.size() / 3;
            logger.fine("[AutoPack] attachables: " + attachableItemCount
                + " custom item(s) received hold-* animation (mode=" + effectiveConfig.mode() + ")");
        }
        if (logger != null && !entityTextureBytes.isEmpty()) {
            int requested = effectiveEntityCopies.size();
            int written = entityTextureBytes.size();
            logger.fine("[AutoPack] entity textures: " + written
                + " override(s) mirrored from Java pack"
                + (written < requested
                    ? " (" + (requested - written) + " dropped due to read failures)"
                    : ""));
        }
    }

    /**
     * Picks the monotonic version sequence to emit. When content is unchanged
     * ({@code contentHash == lastContentHash}), returns {@code lastPatch} so
     * rebuilds stay byte-stable. When content changes, returns
     * {@code max(contentHash, lastPatch + 1)} so Bedrock always sees a
     * strictly higher version for the same UUID (hash-only versions can go
     * down and be ignored by the client).
     *
     * <p>The return value is a <em>sequence</em>, not a patch field: it may
     * exceed {@link #MAX_PACK_PATCH_VERSION}, and
     * {@link #buildManifestJson(int, boolean)} spreads it across
     * {@code version[1]} and {@code version[2]}. Keeping it in one field would
     * saturate — the live sidecar was already at 32219 of 32767, roughly 550
     * content changes from the point where the emitted version stops rising and
     * every Bedrock client silently keeps the pack it already cached.</p>
     *
     * <p>{@code hasLastContentHash} must be {@code false} whenever the caller
     * cannot prove what hash the last emitted patch corresponds to (missing
     * sidecar, unparseable line, no authoritative carry-over). Treating
     * "unknown" as "content changed" is the fail-safe direction: worst case a
     * client re-downloads a byte-identical pack. The reverse — treating
     * "unknown" as "unchanged" — would let a genuinely changed pack keep its
     * old version and leave clients stuck on stale content forever, which is
     * strictly worse. This is also why {@code lastContentHash} alone cannot
     * carry the "unknown" signal: {@code Math.floorMod(-1, 32768) == 32767} is
     * a real, reachable hash value, so an in-band sentinel would make a
     * genuine hash of 32767 indistinguishable from "unknown" and silently
     * suppress a real content-changed bump.</p>
     */
    static int nextMonotonicPatchVersion(
        int contentHash, int lastPatch, int lastContentHash, boolean hasLastContentHash
    ) {
        int hash = Math.floorMod(contentHash, MAX_PACK_PATCH_VERSION + 1);
        if (lastPatch < 0) {
            lastPatch = 0;
        }
        if (lastPatch > 0 && hasLastContentHash
                && hash == Math.floorMod(lastContentHash, MAX_PACK_PATCH_VERSION + 1)) {
            return Math.min(lastPatch, MAX_PACK_SEQUENCE);
        }
        int next = Math.max(hash, lastPatch + 1);
        return Math.min(next, MAX_PACK_SEQUENCE);
    }

    /** {@code version[1]} for a sequence, i.e. how many times patch wrapped. */
    static int sequenceMinor(int sequence) {
        return Math.max(0, sequence) / (MAX_PACK_PATCH_VERSION + 1);
    }

    /** {@code version[2]} for a sequence. */
    static int sequencePatch(int sequence) {
        return Math.max(0, sequence) % (MAX_PACK_PATCH_VERSION + 1);
    }

    /**
     * {@code hasContentHash} makes "no known hash" an explicit flag instead
     * of overloading {@code lastContentHash} with a magic sentinel value —
     * see {@link #nextMonotonicPatchVersion} for why {@code -1} could not be
     * used safely (its floorMod collides with a real content hash of 32767).
     */
    record PackVersionState(int lastPatch, int lastContentHash, boolean hasContentHash) {
        static final PackVersionState EMPTY = new PackVersionState(0, -1, false);
    }

    private static Path packVersionSidecar(Path outputZip) {
        return outputZip.resolveSibling(outputZip.getFileName() + PACK_VERSION_SIDECAR_SUFFIX);
    }

    /**
     * Reads last emitted patch + content hash from the sidecar, falling back
     * to the existing ZIP's manifest patch when the sidecar is missing so the
     * first monotonic build after upgrade still jumps above a high client
     * cache (e.g. 26001).
     */
    static PackVersionState readPackVersionState(Path outputZip, Logger logger) {
        Path sidecar = packVersionSidecar(outputZip);
        if (Files.isRegularFile(sidecar)) {
            try {
                List<String> lines = Files.readAllLines(sidecar, StandardCharsets.UTF_8);
                if (!lines.isEmpty()) {
                    // Strip UTF-8 BOM (PowerShell Set-Content -Encoding UTF8).
                    String patchLine = lines.get(0).trim().replace("\uFEFF", "");
                    int patch = Integer.parseInt(patchLine);
                    int hash = -1;
                    boolean hasHash = false;
                    if (lines.size() > 1) {
                        // A present-but-unparseable second line still leaves
                        // hasHash=false: only a line that actually parses
                        // counts as a known hash, matching the "unknown \u21D2
                        // treat as changed" fail-safe documented on
                        // nextMonotonicPatchVersion.
                        try {
                            hash = Integer.parseInt(lines.get(1).trim().replace("\uFEFF", ""));
                            hasHash = true;
                        } catch (NumberFormatException ignored) {
                            // fall through with hasHash=false
                        }
                    }
                    if (patch >= 0) {
                        return new PackVersionState(patch, hash, hasHash);
                    }
                }
            } catch (Exception ex) {
                if (logger != null) {
                    logger.fine("[AutoPack] pack_version sidecar unreadable ("
                        + ex.getMessage() + ") — falling back to zip manifest");
                }
            }
        }
        int fromZip = readPatchVersionFromZip(outputZip, logger);
        // When building the pending ZIP, also consider the active ZIP's patch
        // so a promote-race cannot let the next pending regress below what
        // clients may already have cached from the active pack.
        int fromActiveSibling = 0;
        boolean carryHash = false;
        int carriedHash = -1;
        String name = outputZip.getFileName().toString();
        if (name.endsWith(".pending.zip")) {
            Path active = outputZip.resolveSibling(
                name.substring(0, name.length() - ".pending.zip".length()) + ".zip");
            int activeZipPatch = readPatchVersionFromZip(active, logger);
            // Recurses into readPackVersionState(active, ...); `active` never
            // ends in ".pending.zip" (the suffix was just stripped off), so
            // this terminates in the sidecar/zip-manifest branches above
            // instead of looping.
            //
            // This branch is the NORMAL path after every promote, not a rare
            // edge case: GeyserExtraExtension.java:369-375 moves the pending
            // sidecar onto the active name as part of promoting a build, so
            // by the time Paper starts again there is routinely no pending
            // sidecar left to read directly — the active sibling's state is
            // the only place the last emitted hash still exists.
            PackVersionState activeSidecar = readPackVersionState(active, logger);
            fromActiveSibling = Math.max(activeZipPatch, activeSidecar.lastPatch());
            // Only trust the active sidecar's hash when it is at least as
            // fresh as everything else on disk for this pack. Without this
            // guard, a stale pending zip left over at a higher version than
            // the active sidecar knows about could get paired with an
            // older hash, making nextMonotonicPatchVersion wrongly report
            // "unchanged" for content that has since moved on.
            if (activeSidecar.hasContentHash()
                    && activeSidecar.lastPatch() >= Math.max(fromZip, activeZipPatch)) {
                carryHash = true;
                carriedHash = activeSidecar.lastContentHash();
            }
        }
        int floor = Math.max(fromZip, fromActiveSibling);
        return floor > 0
            ? new PackVersionState(floor, carriedHash, carryHash)
            : PackVersionState.EMPTY;
    }

    static void writePackVersionState(
        Path outputZip, int patchVersion, int contentHash, Logger logger
    ) {
        Path sidecar = packVersionSidecar(outputZip);
        try {
            String body = patchVersion + "\n" + contentHash + "\n";
            Files.writeString(sidecar, body, StandardCharsets.UTF_8);
        } catch (IOException ex) {
            if (logger != null) {
                logger.warning("[AutoPack] failed to write pack_version sidecar: "
                    + ex.getMessage());
            }
        }
    }

    private static int readPatchVersionFromZip(Path outputZip, Logger logger) {
        if (outputZip == null || !Files.isRegularFile(outputZip)) {
            return 0;
        }
        try (ZipFile zip = new ZipFile(outputZip.toFile())) {
            ZipEntry entry = zip.getEntry("manifest.json");
            if (entry == null) {
                return 0;
            }
            String json = new String(zip.getInputStream(entry).readAllBytes(), StandardCharsets.UTF_8);
            // Minimal parse: "version": [1, 0, N]
            int idx = json.indexOf("\"version\"");
            if (idx < 0) {
                return 0;
            }
            int bracket = json.indexOf('[', idx);
            if (bracket < 0) {
                return 0;
            }
            int end = json.indexOf(']', bracket);
            if (end < 0) {
                return 0;
            }
            String[] parts = json.substring(bracket + 1, end).split(",");
            if (parts.length < 3) {
                return 0;
            }
            // Rebuild the sequence: a pack written after the two-stage counter
            // landed carries the overflow in version[1], and reading only
            // version[2] would floor the sequence back below what clients have
            // already cached.
            int minor = Integer.parseInt(parts[1].trim());
            int patch = Integer.parseInt(parts[2].trim());
            return minor * (MAX_PACK_PATCH_VERSION + 1) + patch;
        } catch (Exception ex) {
            if (logger != null) {
                logger.fine("[AutoPack] could not read patch from existing zip: "
                    + ex.getMessage());
            }
            return 0;
        }
    }

    /**
     * Hashes {@code itemTextureJson} into a 0..32767 integer suitable for use
     * as the patch component of the pack's semantic version. Bedrock treats
     * a (UUID, version) pair as the cache key for resource packs — keeping
     * version[2] tied to content means clients automatically download a
     * fresh copy whenever the registry changes, instead of silently re-using
     * a stale cached pack that no longer matches the live mappings.
     *
     * <p>Range is clamped to 0..32767 because some Bedrock manifest parsers
     * treat each version component as a signed short. SHA-256 is overkill
     * for the collision space we need but is the only reliably-available
     * algorithm in the JDK platform, and the cost is negligible at the
     * mappings.size() scale we handle.</p>
     *
     * <p>Callers must pass this through {@link #nextMonotonicPatchVersion}
     * before writing the manifest — a raw hash can decrease across builds.</p>
     */
    private static int patchVersionFromContent(
        String itemTextureJson,
        Map<String, String> attachableArtifacts,
        Map<String, byte[]> entityTextureBytes,
        Map<String, byte[]> armorTextureBytes,
        Map<String, byte[]> itemTextureBytes
    ) {
        boolean nothingToHash =
            (itemTextureJson == null || itemTextureJson.isEmpty())
            && (attachableArtifacts == null || attachableArtifacts.isEmpty())
            && (entityTextureBytes == null || entityTextureBytes.isEmpty())
            && (armorTextureBytes == null || armorTextureBytes.isEmpty())
            && (itemTextureBytes == null || itemTextureBytes.isEmpty());
        if (nothingToHash) {
            return 0;
        }
        try {
            MessageDigest md = MessageDigest.getInstance("SHA-256");
            if (itemTextureJson != null) {
                md.update(itemTextureJson.getBytes(StandardCharsets.UTF_8));
            }
            if (attachableArtifacts != null && !attachableArtifacts.isEmpty()) {
                // Iterate in deterministic order (the planning step used a
                // LinkedHashMap). Mixing the entry path into the hash means
                // that a rename like attachables/A.json -> attachables/B.json
                // also changes the patch version even when the JSON content
                // is identical.
                for (Map.Entry<String, String> entry : attachableArtifacts.entrySet()) {
                    md.update(entry.getKey().getBytes(StandardCharsets.UTF_8));
                    md.update((byte) 0);
                    if (entry.getValue() != null) {
                        md.update(entry.getValue().getBytes(StandardCharsets.UTF_8));
                    }
                    md.update((byte) 0);
                }
            }
            // Phase 7b (Codex J1 fix): entity texture paths AND pre-read PNG
            // bytes both flow into the hash. Symmetric with the armor path
            // below — single byte buffer drives hash and zip write, so
            // in-place PNG edits always flip the patch version.
            if (entityTextureBytes != null && !entityTextureBytes.isEmpty()) {
                List<String> sorted = new ArrayList<>(entityTextureBytes.keySet());
                java.util.Collections.sort(sorted);
                for (String path : sorted) {
                    md.update("entity:".getBytes(StandardCharsets.UTF_8));
                    md.update(path.getBytes(StandardCharsets.UTF_8));
                    md.update((byte) 0);
                    byte[] bytes = entityTextureBytes.get(path);
                    if (bytes != null) {
                        md.update(bytes);
                    }
                    md.update((byte) 0);
                }
            }
            // Phase 1 (Codex K1 fix): item texture PNG bytes feed the hash
            // alongside their zip paths. Same byte-lockstep pattern as
            // armor/entity — read failures already removed from
            // itemTextureBytes at planning time, so hash and zip stay
            // synchronised even under transient I/O failures.
            if (itemTextureBytes != null && !itemTextureBytes.isEmpty()) {
                List<String> sorted = new ArrayList<>(itemTextureBytes.keySet());
                java.util.Collections.sort(sorted);
                for (String path : sorted) {
                    md.update("item:".getBytes(StandardCharsets.UTF_8));
                    md.update(path.getBytes(StandardCharsets.UTF_8));
                    md.update((byte) 0);
                    byte[] bytes = itemTextureBytes.get(path);
                    if (bytes != null) {
                        md.update(bytes);
                    }
                    md.update((byte) 0);
                }
            }

            // Phase 7a (Codex I1 fix): armor texture iconKeys AND pre-read
            // PNG bytes both flow into the hash. The bytes are passed in
            // from the build() caller after a single readAllBytes pass at
            // the top of the build pipeline, so the same buffer drives the
            // hash here and the zip write below. Entries whose source PNG
            // failed to read were already dropped from the map at planning
            // time, ensuring hash and zip stay in lockstep — no silent
            // path-only fallback that could let zip bytes change without
            // flipping the manifest patch version.
            if (armorTextureBytes != null && !armorTextureBytes.isEmpty()) {
                List<String> sorted = new ArrayList<>(armorTextureBytes.keySet());
                java.util.Collections.sort(sorted);
                for (String iconKey : sorted) {
                    md.update("armor:".getBytes(StandardCharsets.UTF_8));
                    md.update(iconKey.getBytes(StandardCharsets.UTF_8));
                    md.update((byte) 0);
                    byte[] bytes = armorTextureBytes.get(iconKey);
                    if (bytes != null) {
                        md.update(bytes);
                    }
                    md.update((byte) 0);
                }
            }
            byte[] digest = md.digest();
            int value = 0;
            for (int i = 0; i < 4 && i < digest.length; i++) {
                value = (value << 8) | (digest[i] & 0xFF);
            }
            return Math.abs(value) % 32768;
        } catch (NoSuchAlgorithmException ex) {
            // SHA-256 is required by every JDK platform per JEP 414 / spec;
            // this branch should be unreachable. Return 0 as a deterministic
            // fallback rather than throwing — the pack still works without
            // cache busting, just less efficiently.
            return 0;
        }
    }

    /**
     * Planning record for a single Java-pack PNG that will be copied into the
     * generated ZIP. Held in a list so phase 1 (planning) can complete
     * before phase 3 (writing) begins, which is what lets us hash the final
     * item_texture.json into the manifest version without re-walking the
     * mapping set twice.
     */
    /**
     * Renders a 3D model into an inventory icon PNG, or returns {@code null}
     * when this task has no geometry to render or the render came out empty.
     *
     * <p>Never throws: an icon is cosmetic, and a pack build must not fail
     * because one PNG failed to decode. On any error the caller falls back to
     * the existing 2D {@code display.gui} bake.</p>
     */
    private static byte[] renderModelIcon(
        TextureCopyTask task, byte[] rawPng, Logger logger
    ) {
        JavaModelGeometry geometry = task.geometry();
        if (geometry == null || !geometry.hasElements()) {
            return null;
        }
        try {
            java.awt.image.BufferedImage texture =
                javax.imageio.ImageIO.read(new java.io.ByteArrayInputStream(rawPng));
            if (texture == null) {
                return null;
            }
            // Faces naming a layer other than the primary one get their own
            // PNG; anything unresolvable falls back to the primary texture, so
            // a missing side texture paints the main artwork rather than a hole.
            Map<String, java.awt.image.BufferedImage> perFace = new LinkedHashMap<>();
            for (Map.Entry<String, Path> e : task.textureFiles().entrySet()) {
                try {
                    java.awt.image.BufferedImage img =
                        javax.imageio.ImageIO.read(e.getValue().toFile());
                    if (img != null) {
                        perFace.put(e.getKey(), img);
                    }
                } catch (IOException ignored) {
                    // Leave it out; render() falls back to the primary texture.
                }
            }
            java.awt.image.BufferedImage icon = ItemIconRenderer.render(
                geometry, task.gui(), perFace::get, texture,
                ItemIconRenderer.DEFAULT_SIZE, logger);
            if (icon == null) {
                return null;
            }
            java.io.ByteArrayOutputStream out = new java.io.ByteArrayOutputStream();
            if (!javax.imageio.ImageIO.write(icon, "PNG", out)) {
                return null;
            }
            if (logger != null) {
                logger.fine("[AutoPack] rendered 3D inventory icon for " + task.iconKey());
            }
            return out.toByteArray();
        } catch (IOException | RuntimeException ex) {
            if (logger != null) {
                logger.warning("[AutoPack] 3D icon render failed for " + task.iconKey()
                    + " (" + ex.getClass().getSimpleName() + ": " + ex.getMessage()
                    + ") — falling back to the flat display.gui bake");
            }
            return null;
        }
    }

